VALID_UNLOCK_TYPES = {"start", "questions", "keywords"}


def get_case(difficulty: str) -> dict:
    """難易度に対応する事件データを返す（毎回ディープコピー）。"""
    if difficulty not in CASES:
        raise ValueError(f"事件が見つかりません：{difficulty}")
    return copy.deepcopy(CASES[difficulty])


def get_liar_id(case: dict) -> str:
    """嘘つきの容疑者IDを返す。正解はAIではなくデータから取得する。"""
    return next(sid for sid, s in case["suspects"].items() if s["is_liar"])


def validate_case(case: dict) -> None:
    """事件データの整合性をチェックする。問題があれば AssertionError。"""
    suspects = case["suspects"]
    assert 3 <= len(suspects) <= 4, "容疑者は3〜4人に設定してください。"

    ids = list(suspects.keys())
    assert ids == sorted(ids) and ids[0] == "A", "容疑者IDはA, B, C...の連番にしてください。"

    liars = [sid for sid, s in suspects.items() if s["is_liar"]]
    assert len(liars) == 1, "嘘つきは必ず1人に設定してください。"
    liar = suspects[liars[0]]
    assert liar["lie"], "嘘つきには lie（嘘の内容）が必要です。"

    evidence_ids = [e["id"] for e in case["evidence"]]
    assert len(evidence_ids) == len(set(evidence_ids)), "証拠IDが重複しています。"
    assert any(e["unlock"]["type"] == "start" for e in case["evidence"]), (
        "最初から見える証拠が1つ以上必要です。"
    )
    for e in case["evidence"]:
        unlock = e["unlock"]
        assert unlock["type"] in VALID_UNLOCK_TYPES, f"不明な unlock type: {unlock['type']}"
        if unlock["type"] == "keywords":
            assert unlock["words"], "keywords の words が空です。"

    refs = liar.get("contradicted_by", [])
    assert refs, "嘘つきの嘘を崩せる証拠（contradicted_by）が必要です。"
    assert all(r in evidence_ids for r in refs), "contradicted_by に存在しない証拠IDがあります。"

    for sid, s in suspects.items():
        if not s["is_liar"]:
            assert not s["lie"] and not s["cover_lies"], f"{sid}は嘘つきではないので lie は空にしてください。"
            assert "slip" not in s and "contradicted_by" not in s, f"{sid}に嘘つき用の項目があります。"

    assert case["hints"], "ヒントが必要です。"
    assert case["solution"]["logic"], "解説（solution.logic）が必要です。"
